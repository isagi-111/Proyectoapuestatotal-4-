-- Esquema simplificado del Avance 3 (portable: PostgreSQL 14+ y H2 en modo PostgreSQL).
-- El diseño completo con todos los mercados sigue en ../apuesta_total_schema.sql

CREATE TABLE IF NOT EXISTS usuario (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dni_hash    VARCHAR(64) NOT NULL UNIQUE,
    dni_mascara VARCHAR(20) NOT NULL,
    rol         VARCHAR(10) NOT NULL,
    creado_en   TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS billetera (
    usuario_id  BIGINT PRIMARY KEY REFERENCES usuario(id),
    saldo       NUMERIC(14,2) NOT NULL CHECK (saldo >= 0)
);

CREATE TABLE IF NOT EXISTS partido (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    liga          VARCHAR(80) NOT NULL,
    equipo_local  VARCHAR(80) NOT NULL,
    equipo_visita VARCHAR(80) NOT NULL,
    inicio        TIMESTAMP WITH TIME ZONE NOT NULL,
    estado        VARCHAR(12) NOT NULL,
    cuota_local   NUMERIC(6,2) NOT NULL CHECK (cuota_local >= 1.01),
    cuota_empate  NUMERIC(6,2) NOT NULL CHECK (cuota_empate >= 1.01),
    cuota_visita  NUMERIC(6,2) NOT NULL CHECK (cuota_visita >= 1.01),
    goles_local   SMALLINT,
    goles_visita  SMALLINT
);

CREATE TABLE IF NOT EXISTS apuesta (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id         BIGINT NOT NULL REFERENCES usuario(id),
    tipo               VARCHAR(10) NOT NULL,
    estado             VARCHAR(10) NOT NULL,
    monto              NUMERIC(12,2) NOT NULL CHECK (monto > 0),
    cuota_total        NUMERIC(14,2) NOT NULL,
    ganancia_potencial NUMERIC(14,2) NOT NULL,
    creada_en          TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS apuesta_seleccion (
    apuesta_id  BIGINT NOT NULL REFERENCES apuesta(id),
    partido_id  BIGINT NOT NULL REFERENCES partido(id),
    opcion      VARCHAR(10) NOT NULL,
    cuota       NUMERIC(6,2) NOT NULL,
    descripcion VARCHAR(170) NOT NULL,
    PRIMARY KEY (apuesta_id, partido_id)
);

CREATE INDEX IF NOT EXISTS idx_apuesta_usuario ON apuesta(usuario_id);
CREATE INDEX IF NOT EXISTS idx_seleccion_partido ON apuesta_seleccion(partido_id);
